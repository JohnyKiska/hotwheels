"""Encrypted transactional email outbox and provider-neutral dispatcher.

Configure HW_EMAIL_ENCRYPTION_KEY with a Fernet key generated by
cryptography. Raw verification/invitation tokens must never be placed in
unencrypted database columns or audit metadata.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Protocol

from cryptography.fernet import Fernet, InvalidToken
from sqlalchemy import or_, select
from sqlalchemy.orm import Session, sessionmaker

from .models import OutboundEmail, utc_now


class EmailOutboxError(ValueError):
    pass


@dataclass(frozen=True)
class EmailMessage:
    recipient: str
    subject: str
    text_body: str
    html_body: str | None
    idempotency_key: str


class EmailProvider(Protocol):
    def send_email(self, message: EmailMessage) -> None:
        """Send once; providers should honor message.idempotency_key."""


def _fernet() -> Fernet:
    key = os.environ.get("HW_EMAIL_ENCRYPTION_KEY")
    if not key:
        raise EmailOutboxError("email_encryption_key_not_configured")
    try:
        return Fernet(key.encode("ascii"))
    except (ValueError, UnicodeEncodeError) as exc:
        raise EmailOutboxError("invalid_email_encryption_key") from exc


def queue_email(
    db: Session,
    *,
    recipient: str,
    subject: str,
    text_body: str,
    idempotency_key: str,
    html_body: str | None = None,
) -> OutboundEmail:
    recipient = recipient.strip().casefold()
    if not recipient or len(recipient) > 320 or "@" not in recipient:
        raise EmailOutboxError("invalid_recipient")
    if not subject.strip() or len(subject) > 250:
        raise EmailOutboxError("invalid_subject")
    if not text_body.strip() or len(text_body) > 100_000:
        raise EmailOutboxError("invalid_text_body")
    if html_body is not None and len(html_body) > 200_000:
        raise EmailOutboxError("html_body_too_large")
    if not idempotency_key or len(idempotency_key) > 180:
        raise EmailOutboxError("invalid_idempotency_key")

    existing = db.scalar(select(OutboundEmail).where(
        OutboundEmail.idempotency_key == idempotency_key
    ))
    if existing is not None:
        if existing.recipient_email != recipient:
            raise EmailOutboxError("idempotency_key_conflict")
        return existing

    payload = json.dumps({
        "subject": subject,
        "text_body": text_body,
        "html_body": html_body,
    }, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    encrypted = _fernet().encrypt(payload).decode("ascii")
    message = OutboundEmail(
        recipient_email=recipient,
        encrypted_payload=encrypted,
        status="pending",
        idempotency_key=idempotency_key,
        attempt_count=0,
        available_at=utc_now(),
    )
    db.add(message)
    db.flush()
    return message


def _decode_message(row: OutboundEmail, cipher: Fernet | None = None) -> EmailMessage:
    try:
        payload = json.loads((cipher or _fernet()).decrypt(
            row.encrypted_payload.encode("ascii")
        ).decode("utf-8"))
    except (InvalidToken, ValueError, UnicodeDecodeError) as exc:
        raise EmailOutboxError("email_payload_decryption_failed") from exc
    return EmailMessage(
        recipient=row.recipient_email,
        subject=payload["subject"],
        text_body=payload["text_body"],
        html_body=payload.get("html_body"),
        idempotency_key=row.idempotency_key,
    )


def _aware(value: datetime) -> datetime:
    if value.tzinfo is None:
        return value.replace(tzinfo=timezone.utc)
    return value


def dispatch_outbox_batch(
    session_factory: sessionmaker,
    provider: EmailProvider,
    *,
    now: datetime | None = None,
    limit: int = 20,
    lease: timedelta = timedelta(minutes=10),
    max_attempts: int = 5,
) -> dict[str, int]:
    """Claim in a short transaction, send outside it, then record each result."""
    if limit < 1 or limit > 100 or max_attempts < 1:
        raise EmailOutboxError("invalid_dispatch_limits")
    now = now or utc_now()
    cipher = _fernet()  # fail before claiming rows if the encryption key is absent
    claimed: list[tuple[str, EmailMessage]] = []
    decode_failed = 0

    with session_factory() as db:
        eligible = or_(
            (OutboundEmail.status == "pending") & (OutboundEmail.available_at <= now),
            (OutboundEmail.status == "sending")
            & (OutboundEmail.locked_at.is_not(None))
            & (OutboundEmail.locked_at <= now - lease),
        )
        rows = db.scalars(
            select(OutboundEmail)
            .where(eligible)
            .order_by(OutboundEmail.created_at, OutboundEmail.id)
            .limit(limit)
            .with_for_update(skip_locked=True)
        ).all()
        for row in rows:
            row.status = "sending"
            row.locked_at = now
            row.attempt_count += 1
            try:
                message = _decode_message(row, cipher)
            except EmailOutboxError:
                row.status = "failed"
                row.locked_at = None
                row.last_error = "payload_decryption_failed"
                decode_failed += 1
                continue
            claimed.append((row.id, message))
        db.commit()

    result = {"sent": 0, "retrying": 0, "failed": decode_failed}
    for message_id, message in claimed:
        try:
            provider.send_email(message)
        except Exception as exc:  # provider errors must not expose message secrets
            with session_factory() as db:
                row = db.get(OutboundEmail, message_id)
                if row is None or row.status != "sending":
                    continue
                row.locked_at = None
                row.last_error = f"delivery_error:{type(exc).__name__}"[:500]
                if row.attempt_count >= max_attempts:
                    row.status = "failed"
                    result["failed"] += 1
                else:
                    row.status = "pending"
                    delay_minutes = min(2 ** row.attempt_count, 60)
                    row.available_at = now + timedelta(minutes=delay_minutes)
                    result["retrying"] += 1
                db.commit()
        else:
            with session_factory() as db:
                row = db.get(OutboundEmail, message_id)
                if row is None or row.status != "sending":
                    continue
                row.status = "sent"
                row.sent_at = utc_now()
                row.locked_at = None
                row.last_error = None
                db.commit()
                result["sent"] += 1
    return result
